// Runs the Karachi data pipeline (docs/05-data-strategy.md):
//   1 parse     raw/Bus-Routes-Karachi.txt -> build/routes.json
//   2 gazetteer routes -> gazetteer.json (+ merge candidates in build/review.md)
//   3 osm-match osm/places.json -> build/osm-suggestions.json (skipped if there's no OSM export)
//   4 network   gazetteer + OSM locations -> network.json, also copied to the app's mock fixture
//
// Usage (from the repo root): node data/karachi/pipeline/run.mjs

import { writeFileSync, existsSync } from 'node:fs';
import { p, readJson } from './lib.mjs';
import { runParse } from './1-parse.mjs';
import { runGazetteer } from './2-gazetteer.mjs';
import { runOsmMatch } from './3-osm-match.mjs';
import { runNetwork } from './4-network.mjs';

const parsed = runParse();
const { places, routes, candidates, autoMerged, routeMerges } = runGazetteer(parsed);
// Without the raw Overpass export (it isn't committed), reuse the committed suggestions.
const osm = runOsmMatch(places) ??
  (existsSync(p('build/osm-suggestions.json')) ? { cached: true, ...readJson(p('build/osm-suggestions.json')) } : null);
if (osm?.cached) console.log('osm: no osm/places.json, using the committed build/osm-suggestions.json');
const net = runNetwork({ places, routes, osm });
const N = net.network;

const live = places.filter((pl) => !pl.unused);
const shared = live.filter((pl) => pl.routeCount >= 2);
const flagged = parsed.filter((r) => r.flags.length);
const withLoc = live.filter((pl) => pl.location).length;
const withUr = live.filter((pl) => pl.name.ur).length;

const md = [];
md.push('# Karachi data review', '', '_Generated by `pipeline/run.mjs`. Do not edit; re-run the pipeline._', '');
md.push('## Summary', '');
md.push(`- Routes: **${routes.length}** after merging ${routeMerges.length} duplicate listing(s) (${routes.filter((r) => r.kind === 'minibus').length} numbered, ${routes.filter((r) => r.kind === 'coach').length} coaches), ${routes.reduce((a, r) => a + r.stops.length, 0)} stop mentions`);
md.push(`- Unique places: **${live.length}**, of which ${shared.length} are on 2+ routes (possible transfer points) and ${live.length - shared.length} on one route only`);
md.push(`- Places with coordinates: ${withLoc}/${live.length} · with Urdu name: ${withUr}/${live.length}`);
md.push(`- Roads (corridors, not points; need per-route handling before they can be stops): ${live.filter((pl) => pl.kind === 'road').length}, covering ${live.filter((pl) => pl.kind === 'road').reduce((a, pl) => a + pl.routeCount, 0)} stop mentions`);
md.push(`- Places auto-merged: ${autoMerged.reduce((a, c) => a + c.spellings.length, 0)} spellings folded into ${autoMerged.length} places (D34)`);
md.push(`- Possible duplicate places still to review: ${candidates.length} · generic names that may hide several places: ${live.filter((pl) => pl.generic).length}`);
if (osm) if (osm?.cached) md.push('- OSM suggestions: reused from the committed `build/osm-suggestions.json` (no fresh Overpass export)');
else if (osm) md.push(`- OSM suggestions: ${osm.exact} exact, ${osm.core} same-name-minus-suffix, ${osm.fuzzy} fuzzy, ${osm.none} none (from ${osm.features} OSM features); ${osm.ambiguous} ambiguous (candidates >500 m apart); ${osm.withUr} offer an Urdu name`);
else md.push('- OSM matches: not run (no `osm/places.json` yet; see README)');
md.push(`- **network.json: ${N.routes.length} routes (${N.variants.length} variants), ${N.stops.length} stops**; ${routes.length - N.routes.length} routes left out (fewer than 2 located stops). ${net.urFromOsm} stop Urdu names from OSM, ${N.stops.filter((s) => s.name.ur === s.name.en).length} fall back to English. All unverified.`);
md.push('');

md.push('## Network coverage', '');
{
  const kept = net.report.filter((r) => r.kept >= 2);
  const pct = (r) => r.kept / r.total;
  const buckets = [[0.75, 1.01], [0.5, 0.75], [0.25, 0.5], [0, 0.25]];
  md.push('Share of each route\'s listed stops that made it into the network (the rest have no usable location yet):', '');
  for (const [lo, hi] of buckets) md.push(`- ${Math.round(lo * 100)}–${Math.min(100, Math.round(hi * 100))}%: ${kept.filter((r) => pct(r) >= lo && pct(r) < hi).length} routes`);
  const out = net.report.filter((r) => r.kept < 2);
  md.push(`- Left out entirely: ${out.length} routes${out.length ? ' (' + out.map((r) => r.key).join(', ') + ')' : ''}`, '');
  const off = net.report.filter((r) => r.offRoute.length);
  if (off.length) {
    md.push('Stops dropped from a route because their OSM location sends the route far off and back (likely a wrong match):', '');
    for (const r of off) md.push(`- **${r.key}**: ${r.offRoute.join(', ')}`);
    md.push('');
  }
  const byReason = new Map();
  for (const [id, reason] of net.why) {
    const pl = places.find((x) => x.id === id);
    const k = reason.startsWith('location looks wrong') ? 'location looks wrong' : reason;
    byReason.set(k, [...(byReason.get(k) ?? []), { pl, reason }]);
  }
  md.push('Busiest places with no location in the network (fill these in `gazetteer.json` to add the most stops):', '');
  md.push('| Place | routes | why |', '| --- | --- | --- |');
  for (const { pl, reason } of [...byReason.values()].flat().sort((a, b) => b.pl.routeCount - a.pl.routeCount).slice(0, 50)) md.push(`| ${pl.name.en} | ${pl.routeCount} | ${reason} |`);
  md.push('');
}

md.push('## Routes needing a look', '');
for (const r of flagged) md.push(`- **${r.key}** (line ${r.line}): ${r.flags.join('; ')}`);
md.push('');

md.push('## Auto-merged places', '');
md.push('Near-spellings merged automatically. If one is wrong, add the pair to `doNotMerge` in `aliases.json` (e.g. `["Clifton Road", "Clayton Road"]`) and re-run.', '');
for (const c of [...autoMerged].sort((a, b) => b.into.routeCount - a.into.routeCount)) md.push(`- **${c.into.name.en}** ← ${c.spellings.join(', ')}`);
md.push('');

md.push('## Possible duplicate places', '');
md.push('If a pair is the same place, add it to `aliases.json` and re-run. **Different numbers are never paired** (Orangi 4 ≠ Orangi 5). Contained names ("Malir" / "Malir City") are often *different* places, so check before merging.', '');
md.push('| Place A | routes | Place B | routes | similarity |', '| --- | --- | --- | --- | --- |');
for (const c of candidates) {
  md.push(`| ${c.a.name.en} | ${c.a.routeCount} | ${c.b.name.en} | ${c.b.routeCount} | ${c.contained && c.sim < 0.8 ? 'contains' : c.sim.toFixed(2)} |`);
}
md.push('');

const generic = live.filter((pl) => pl.generic);
md.push('## Generic names', '');
md.push('These names could mean different places on different routes (one route\'s "Petrol Pump" may not be another\'s). Check each route\'s neighbouring stops; where it is a different place, rename it for that route under `routeOverrides` in `aliases.json` (e.g. `"1-A": { "Petrol Pump": "Nazimabad Petrol Pump" }`).', '');
for (const pl of generic) md.push(`- **${pl.name.en}** (${pl.routeCount} routes): ${pl.routes.slice(0, 12).join(', ')}${pl.routes.length > 12 ? ', …' : ''}`);
md.push('');

if (osm) {
  const sug = new Map(osm.suggestions.map((s) => [s.id, s]));
  md.push('## OSM suggestions for the busiest places (top 80)', '');
  md.push('Best candidate first (junctions/places/stops rank above shops and mosques). Full candidate lists are in `build/osm-suggestions.json`. Check each on the map before copying into `gazetteer.json`. ⚠ = candidates more than 500 m apart, so pick using the route\'s neighbouring stops.', '');
  md.push('| Place | routes | best OSM match | type | lat, lng | Urdu (OSM) | note |', '| --- | --- | --- | --- | --- | --- | --- |');
  for (const pl of live.slice(0, 80)) {
    const s = sug.get(pl.id);
    const tag = pl.kind === 'road' ? 'road' : pl.generic ? 'generic' : '';
    if (!s) { md.push(`| ${pl.name.en} | ${pl.routeCount} | — | | | | ${tag || 'no match: find by hand'} |`); continue; }
    const c = s.candidates[0];
    const ur = s.candidates.find((x) => x.ur)?.ur ?? '';
    md.push(`| ${pl.name.en} | ${pl.routeCount} | ${c.names[0]} (${c.match}) | ${c.kind} | ${c.lat}, ${c.lng} | ${ur} | ${[s.ambiguous ? `⚠ ${s.candidates.length} candidates, ${s.spreadKm} km apart` : '', tag].filter(Boolean).join('; ')} |`);
  }
  md.push('');
}

md.push('## Places by number of routes (top 60)', '', 'Do these first: coordinates and Urdu names for the busiest places unlock the most routes.', '');
md.push('| Place | routes | spellings seen |', '| --- | --- | --- |');
for (const pl of live.slice(0, 60)) md.push(`| ${pl.name.en} | ${pl.routeCount} | ${pl.aliases.slice(0, 6).join(', ')}${pl.aliases.length > 6 ? ', …' : ''} |`);
md.push('');
writeFileSync(p('build/review.md'), md.join('\n'));

console.log(`routes ${routes.length} (${flagged.length} flagged) · places ${live.length} (${shared.length} shared) · merge candidates ${candidates.length}`);
console.log(osm?.cached ? 'osm: cached suggestions' : osm ? `osm: ${osm.exact} exact, ${osm.core} suffix, ${osm.fuzzy} fuzzy, ${osm.none} unmatched · ${osm.ambiguous} ambiguous · ${osm.withUr} with Urdu` : 'osm: skipped (no osm/places.json)');
console.log(`network: ${N.routes.length} routes, ${N.variants.length} variants, ${N.stops.length} stops (${routes.length - N.routes.length} routes left out)`);
console.log('wrote build/routes.json, gazetteer.json, build/review.md, network.json, app fixture' + (osm ? ', build/osm-suggestions.json' : ''));
