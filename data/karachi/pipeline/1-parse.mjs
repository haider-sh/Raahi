// Step 1 · Parse raw/Bus-Routes-Karachi.txt into ordered stop lists.
// Output: build/routes.json. Anything odd is flagged per route, never silently "fixed".

import { readFileSync } from 'node:fs';
import { p, writeJson } from './lib.mjs';

export function parse(text) {
  const lines = text.replace(/\r/g, '').split('\n');
  const routes = [];
  let cur = null;
  let body = [];

  const flush = () => {
    if (!cur) return;
    // Join wrapped lines. The source was copied from a PDF, so a line break can fall mid-name
    // ("Sabilwali\nMasjid"): join with a space, or with nothing after a trailing hyphen
    // ("Shahrah-e-\nQaideen").
    let joined = '';
    for (const l of body) {
      if (!joined) joined = l;
      else if (/-$/.test(joined)) joined += l;
      else joined += ' ' + l;
    }
    const stops = [];
    for (let raw of joined.split(',')) {
      raw = raw.replace(/\s+/g, ' ').trim();
      if (!raw) continue;
      const note = raw.match(/\((.*?)\)/)?.[1] ?? null;
      const name = raw.replace(/\(.*?\)/g, ' ').replace(/\s+/g, ' ').trim();
      if (!name) {
        cur.flags.push(`empty stop after removing note "${raw}"`);
        continue;
      }
      // "Coast guard, (HQ) Mansfield street": a note opening a stop likely belongs to the previous one.
      if (note && raw.startsWith('(') && stops.length) {
        cur.flags.push(`note "(${note})" before "${name}" may belong to "${stops.at(-1).name}"`);
      }
      stops.push(note ? { name, note } : { name });
    }
    if (stops.length && stops.at(-1).name.length <= 3 && !/\d/.test(stops.at(-1).name)) {
      cur.flags.push(`last stop "${stops.at(-1).name}" looks truncated; dropped`);
      stops.pop();
    }
    if (stops.length < 2) cur.flags.push(`only ${stops.length} stop(s)`);
    cur.stops = stops;
    routes.push(cur);
    cur = null;
    body = [];
  };

  lines.forEach((line, i) => {
    const t = line.trim();
    const m = t.match(/^Route #:\s*(.+)$/);
    if (m) {
      flush();
      cur = { code: m[1].trim(), line: i + 1, flags: [], stops: [] };
      return;
    }
    if (!cur) return; // file header
    if (/^Stops:$/.test(t)) return;
    if (!t || /^https?:\/\//.test(t)) return;
    body.push(t);
  });
  flush();

  // Duplicate codes: keep every entry, give each a unique key, flag for review.
  const byCode = new Map();
  for (const r of routes) byCode.set(r.code, [...(byCode.get(r.code) ?? []), r]);
  for (const [code, group] of byCode) {
    if (group.length === 1) {
      group[0].key = code;
      continue;
    }
    group.forEach((r, i) => {
      r.key = `${code}#${i + 1}`;
      const overlap = (a, b) => {
        const A = new Set(a.stops.map((s) => s.name.toLowerCase()));
        return b.stops.filter((s) => A.has(s.name.toLowerCase())).length / Math.max(b.stops.length, 1);
      };
      const others = group.filter((o) => o !== r);
      const maxOverlap = Math.max(...others.map((o) => overlap(o, r)));
      r.flags.push(
        `code "${code}" appears ${group.length} times (` +
          (maxOverlap > 0.5 ? 'probably the same route listed twice' : 'looks like a different route') +
          `, ${Math.round(maxOverlap * 100)}% stop overlap)`,
      );
    });
  }

  for (const r of routes) {
    r.kind = /coach/i.test(r.code) ? 'coach' : 'minibus';
  }
  return routes;
}

export function runParse() {
  const text = readFileSync(p('raw/Bus-Routes-Karachi.txt'), 'utf8');
  const routes = parse(text);
  writeJson(p('build/routes.json'), {
    source: 'raw/Bus-Routes-Karachi.txt',
    note: 'Generated by pipeline/1-parse.mjs. Do not edit; fix the parser or the raw file instead.',
    routes: routes.map(({ key, code, kind, line, flags, stops }) => ({ key, code, kind, line, flags, stops })),
  });
  return routes;
}
